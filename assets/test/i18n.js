export function normalizeLanguage(language) {
  return SUPPORTED_LANGUAGES.includes(language) ? language : 'uk';
}

export function copyFor(language) {
  return common[normalizeLanguage(language)];
}

export function translateStaticDocument(document, language) {
  const copy = copyFor(language);
  document.documentElement.lang = normalizeLanguage(language);
  const audience = document.body?.dataset?.testAudience === 'research' ? 'research' : 'public';
  document.title = copy[`page.${audience}Title`];
  const description = document.querySelector('meta[name="description"]');
  if (description) description.setAttribute('content', copy[`page.${audience}Description`]);
  document.querySelectorAll('[data-i18n]').forEach(element => {
    const value = copy[element.dataset.i18n];
    if (typeof value === 'string') element.textContent = value;
  });
  document.querySelectorAll('[data-i18n-aria-label]').forEach(element => {
    const value = copy[element.dataset.i18nAriaLabel];
    if (typeof value === 'string') element.setAttribute('aria-label', value);
  });
}
